#!/usr/bin/env node
// Builds src/brain/providers/waifu-archive-index.js from the Waifu archive's
// PostgreSQL export (waifu-public.sql), so the bot can pick an archive image
// without asking the archive's search API first.
//
//   node scripts/build-waifu-archive-index.mjs path/to/waifu-public.sql

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The tags the bot's commands use; the order defines the bit in each mask.
const TAGS = ['ass', 'ecchi', 'ero', 'hentai', 'maid', 'milf', 'oppai', 'oral', 'paizuri', 'selfies', 'uniform', 'waifu'];
const OUTPUT = fileURLToPath(new URL('../src/brain/providers/waifu-archive-index.js', import.meta.url));

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/build-waifu-archive-index.mjs path/to/waifu-public.sql');
  process.exit(1);
}
const lines = readFileSync(source, 'utf8').split('\n');

// Rows of a `COPY public."<table>" (...) FROM stdin;` block, by column name.
function copyRows(table) {
  const start = lines.findIndex((line) => line.startsWith(`COPY public."${table}" (`));
  if (start === -1) throw new Error(`The export has no ${table} table.`);
  const columns = lines[start].match(/\(([^)]*)\)/)[1].split(',').map((column) => column.trim().replaceAll('"', ''));
  const rows = [];
  for (const line of lines.slice(start + 1)) {
    if (line === '\\.') break;
    const values = line.split('\t');
    rows.push(Object.fromEntries(columns.map((column, index) => [column, values[index]])));
  }
  return rows;
}

const tagBits = new Map();
for (const tag of copyRows('Tags')) {
  const index = TAGS.indexOf(tag.Slug);
  if (index !== -1) tagBits.set(tag.Id, 1 << index);
}
const images = new Map();
for (const image of copyRows('Images')) {
  if (image.IsNsfw !== 't') continue;
  if (!/^\.(?:gif|jpe?g|png|webp)$/i.test(image.Extension)) continue;
  images.set(image.Id, { id: Number(image.Id), extension: image.Extension, kib: Math.ceil(Number(image.ByteSize) / 1024), mask: 0 });
}
for (const link of copyRows('ImageTag')) {
  const image = images.get(link.ImagesId);
  const bit = tagBits.get(link.TagsId);
  if (image && bit) image.mask |= bit;
}

const entries = [...images.values()].filter((image) => image.mask).sort((left, right) => left.id - right.id);
const data = entries.map((image) => `${image.id}${image.extension}:${image.kib}:${image.mask.toString(36)}`);
const lines80 = [];
for (let index = 0; index < data.length; index += 8) lines80.push(`  '${data.slice(index, index + 8).join(' ')}',`);

writeFileSync(OUTPUT, `// Generated by scripts/build-waifu-archive-index.mjs from the Waifu archive's
// database export. Do not edit by hand; rebuild it if the archive changes.
//
// Every NSFW archive image under a tag the bot uses, as
// "<id><extension>:<size in KiB, rounded up>:<tag mask in base 36>".

export const ARCHIVE_TAGS = Object.freeze([${TAGS.map((tag) => `'${tag}'`).join(', ')}]);

export const ARCHIVE_IMAGES = [
${lines80.join('\n')}
].join(' ');
`);
console.log(`Wrote ${entries.length} images to ${OUTPUT}.`);
